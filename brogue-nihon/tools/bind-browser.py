"""Produce web bindings with the exact CLI version pinned by the Rust lockfile."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parent.parent

def bind(source, output):
    lock = tomllib.loads((ROOT / 'rust/Cargo.lock').read_text(encoding='utf-8'))
    version = next(package['version'] for package in lock['package'] if package['name'] == 'wasm-bindgen')
    executable = os.environ.get('BROGUE_WASM_BINDGEN') or shutil.which('wasm-bindgen')
    if not executable:
        raise RuntimeError(f'Install wasm-bindgen-cli {version} or set BROGUE_WASM_BINDGEN')
    actual = subprocess.check_output([executable, '--version'], text=True).strip()
    if actual != f'wasm-bindgen {version}':
        raise RuntimeError(f'Expected wasm-bindgen {version}, got {actual}')
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    subprocess.run([executable, str(source), '--target', 'web', '--no-typescript', '--out-dir', str(output), '--out-name', 'browser-ui'], check=True)
    generated = output / 'browser-ui.js'
    code = generated.read_text(encoding='utf-8').replace('browser-ui_bg.wasm', 'browser-ui.wasm')
    generated.write_text(f'// Generated by wasm-bindgen {version} from brogue-browser-ui.\n' + code, encoding='utf-8', newline='\n')
    (output / 'browser-ui_bg.wasm').replace(output / 'browser-ui.wasm')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    bind(args.source, args.output)
